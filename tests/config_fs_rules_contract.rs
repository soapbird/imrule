#[test]
fn concatenate_rules_matches_native_section_format() {
    let tmp = tempdir().unwrap();
    let base = tmp.path();
    let files = vec![
        (
            base.join(".imrule/AGENTS.md"),
            "\n# Root Rules\n\nPrimary rule.\n\n".to_string(),
        ),
        (
            base.join(".imrule/nested/extra.md"),
            "# Extra Rules\n\nSecondary rule.\n".to_string(),
        ),
    ];

    let actual = concatenate_rules(&files, Some(base));

    assert_eq!(
        actual,
        "\n\n<!-- Source: .imrule/AGENTS.md -->\n\n# Root Rules\n\nPrimary rule.\n\n\n\n<!-- Source: .imrule/nested/extra.md -->\n\n# Extra Rules\n\nSecondary rule.\n"
    );
}

#[test]
fn read_markdown_files_orders_primary_skips_skills_and_agents_by_default() {
    let tmp = tempdir().unwrap();
    let root = tmp.path();
    let imrule_dir = root.join(".imrule");
    fs::create_dir_all(imrule_dir.join("skills/demo")).unwrap();
    fs::create_dir_all(imrule_dir.join("agents")).unwrap();
    fs::create_dir_all(imrule_dir.join("z")).unwrap();
    fs::write(imrule_dir.join("z/last.md"), "last").unwrap();
    fs::write(imrule_dir.join("AGENTS.md"), "primary").unwrap();
    fs::write(imrule_dir.join("alpha.md"), "alpha").unwrap();
    fs::write(imrule_dir.join("skills/demo/SKILL.md"), "skill").unwrap();
    fs::write(imrule_dir.join("agents/helper.md"), "agent").unwrap();
    fs::write(
        root.join("AGENTS.md"),
        "<!-- Generated by ImRule -->\n\n<!-- Source: .imrule/AGENTS.md -->\nold",
    )
    .unwrap();

    let fs = FsFileSystem::new();
    let files = fs.read_markdown_files(&imrule_dir, false).unwrap();
    let rels: Vec<_> = files
        .iter()
        .map(|(path, _)| {
            path.strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/")
        })
        .collect();

    assert_eq!(
        rels,
        vec![".imrule/AGENTS.md", ".imrule/alpha.md", ".imrule/z/last.md"]
    );
}

